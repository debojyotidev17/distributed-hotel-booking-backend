import jwt from "jsonwebtoken";

import { serverConfig } from "../../config/server.config.js";
import { UnauthorizedError } from "../errors/app.error.js";

// Generates an access token for an authenticated user.
export const generateAccessToken = (userId: string): string => {
    return jwt.sign({ userId }, serverConfig.JWT_SECRET, { expiresIn: "1h" });
};

// Verifies an access token and returns the user ID.
export const verifyAccessToken = (token: string): string => {
    try {
        const decoded = jwt.verify(token, serverConfig.JWT_SECRET);
        /*
        It performs three important checks:
    
        1. Checks whether the JWT signature is valid using your secret key.
        2. Checks whether the token has expired.
        3. Returns the decoded payload if verification succeeds.
        */

        // a token can have a valid signature but still lack the userId property if it was generated by some other trusted code using the same secret.

        /*
        with the jsonwebtoken library, the JWT payload can be either:
        1. An object (JSON object)
        2. A string
        */
        if (typeof decoded === "string" || typeof decoded.userId !== "string") {
            throw new Error("Invalid access token");
        }

        return decoded.userId;
    } catch (error) { 
        throw new UnauthorizedError("Invalid or expired access token");
    }
};
